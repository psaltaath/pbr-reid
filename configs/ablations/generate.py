def _yaml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_yaml_value(x) for x in v) + "]"
    return str(v)


def render(description, flat):
    nested = {}
    for key, value in flat.items():
        section, name = key.split(".", 1)
        nested.setdefault(section, {})[name] = value
    lines = [f"# {description}", "# Generated by configs/ablations/generate.py — do not edit by hand."]
    for section in sorted(nested):
        lines.append(f"{section}:")
        for name, value in nested[section].items():
            lines.append(f"  {name}: {_yaml_value(value)}")
    return "\n".join(lines) + "\n"


def main():
    for group, items in GROUPS.items():
        out_dir = HERE / group
        out_dir.mkdir(parents=True, exist_ok=True)
        for name, (description, flat) in items.items():
            (out_dir / f"{name}.yaml").write_text(render(description, flat))
            print(f"  wrote {group}/{name}.yaml")


if __name__ == "__main__":
    main()
